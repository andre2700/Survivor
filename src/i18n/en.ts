/** número no formato português (1.000 · 1,5) para o inglês (1,000 · 1.5) */
const enNumber = (v: string) => (/^[+\-]?\d{1,3}(\.\d{3})+$/.test(v) ? v.replace(/\./g, ',') : /^[+\-]?\d+,\d+$/.test(v) ? v.replace(',', '.') : v);

const esc = (s: string) => s.replace(/[.*+?^$()|[\]\\]/g, '\\$&');

function compile([pt, en]: [string, string]): Pattern {
  const parts = pt.split('{}').map(esc);
  const re = new RegExp(`^${parts.join('(.+?)')}$`, 'i');
  return [re, (m, tr) => {
    let i = 0;
    return en.replace(/\{(\d*)\}/g, (_, n: string) => {
      const v = m[n ? Number(n) : ++i] ?? '';
      // número fica como está; texto é traduzido de novo (nome de criatura, raridade...)
      return /[A-Za-zÀ-ú]{2}/.test(v) ? tr(v) : enNumber(v);
    });
  }];
}

/** Número (ou porcentagem) seguido de texto: "+15% de dano" → "+15% damage". */
const NUMBERED: Pattern[] = [
  [/^([+\-−×]?[\d.,]+[%×xKMB]?) (.+)$/i, (m, _tr, peek) => {
    const rest = m[2].replace(/^de /, '');
    const t = EN[`de ${rest}`] ?? peek(rest);
    return t === undefined ? undefined : `${m[1]} ${t}`;
  }],
  // "Nome (Raridade)" e "PALAVRA!": cada parte traduzida
  [/^(.+) \((.+)\)$/, (m, _tr, peek) => {
    const a = peek(m[1]);
    const b = peek(m[2]) ?? (/^[\d\s.,%+\-/]+$/.test(m[2]) ? m[2] : undefined);
    return a === undefined || b === undefined ? undefined : `${a} (${b})`;
  }],
  [/^(.+)!$/, (m, _tr, peek) => {
    const t = peek(m[1]);
    return t === undefined ? undefined : `${t}!`;
  }],
  // texto seguido de número: "Corpo a corpo 1"
  [/^(.+?) ([\d.,]+)$/, (m, _tr, peek) => {
    const t = peek(m[1]);
    return t === undefined ? undefined : `${t} ${m[2]}`;
  }],
];

export const EN_PATTERNS: Pattern[] = [...P.map(compile), ...NUMBERED];
